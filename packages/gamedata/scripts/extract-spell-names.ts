// Extracts the names of the spells the engine knows from an upstream wowsims/forever checkout into
// data/spell-names/spell-names.json.
//
//   node packages/gamedata/scripts/extract-spell-names.ts --upstream <path to forever checkout>
//
// The engine reports abilities and auras by spell id. db.bin's `spellIcons` names about 2,000 of them; the
// rest (Windfury Weapon's strike 439440, weapon-imbue procs, consumable auras, ...) are only named in the
// engine's own spell table, `sim/core/spelldata/spells_auto_gen.go` (generated upstream from the game's DBC).
// This keeps the id, name and rank of every spell there that `spellIcons` does not already name, so the app
// can name them offline. No Go and no network: plain Node reading the Go source.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const repo = path.resolve(pkg, '../..');
const outDir = path.join(pkg, 'data/spell-names');

const arg = (name: string): string | undefined => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const upstream = path.resolve(arg('upstream') ?? process.env['FOREVER_UPSTREAM'] ?? '');
const SPELLS = 'sim/core/spelldata/spells_auto_gen.go';
const DB = 'assets/database/db.json';
if (!existsSync(path.join(upstream, SPELLS))) {
  console.error('Pass --upstream <wowsims/forever checkout> (or FOREVER_UPSTREAM).');
  process.exit(1);
}
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim();
const lock = JSON.parse(readFileSync(path.join(repo, 'engine.lock.json'), 'utf8')) as {
  upstream: { commit: string };
};
if (lock.upstream.commit !== commit) {
  console.warn(`warning: upstream is at ${commit}, engine.lock.json pins ${lock.upstream.commit}`);
}

const db = JSON.parse(readFileSync(path.join(upstream, DB), 'utf8')) as {
  spellIcons?: { id: number; name?: string }[];
};
const named = new Set((db.spellIcons ?? []).filter((s) => s.name).map((s) => s.id));

// One spell per line: `\t{ID: 439440, Name: "Windfury Weapon", Rank: "Rank 1", School: 1, ...`
const source = readFileSync(path.join(upstream, SPELLS), 'utf8');
const LINE = /^\t\{ID: (\d+), Name: "((?:[^"\\]|\\.)*)"(?:, Rank: "((?:[^"\\]|\\.)*)")?/gm;
const spells: [number, string, number][] = [];
let total = 0;
for (const m of source.matchAll(LINE)) {
  total++;
  const id = Number(m[1]);
  const name = JSON.parse(`"${m[2]}"`) as string;
  if (!name || named.has(id)) continue;
  const rank = Number(/^Rank (\d+)$/.exec(m[3] ?? '')?.[1] ?? 0);
  spells.push([id, name, rank]);
}
if (total < 1000) {
  console.error(`only ${total} spells parsed from ${SPELLS}; has its format changed?`);
  process.exit(1);
}
spells.sort((a, b) => a[0] - b[0]);

mkdirSync(outDir, { recursive: true });
const data = {
  upstream: { repo: 'wowsims/forever', commit, files: [SPELLS, DB] },
  // [spell id, name, rank (0 when the spell has none)]
  spells,
};
writeFileSync(path.join(outDir, 'spell-names.json'), JSON.stringify(data) + '\n');
writeFileSync(
  path.join(outDir, 'README.md'),
  `# Spell names

Generated by \`scripts/extract-spell-names.ts\` from [wowsims/forever](https://github.com/wowsims/forever) (MIT) at
\`${commit}\`: the id, name and rank of every spell in the engine's spell table (\`${SPELLS}\`) that
\`${DB}\`'s \`spellIcons\` (the same table db.bin carries) does not already name. Do not edit by hand; rerun the
script (engine-sync does, see \`tools/engine-build/README.md\`):

\`\`\`sh
node packages/gamedata/scripts/extract-spell-names.ts --upstream <forever checkout>
\`\`\`

The app loads it lazily (\`loadSpellNames\` in \`src/spell-names.ts\`) to name abilities and auras the engine reports
by spell id. ${spells.length} of the table's ${total} spells are here.
`,
);
console.log(`wrote ${spells.length} of ${total} spell names to ${path.relative(repo, outDir)}`);
