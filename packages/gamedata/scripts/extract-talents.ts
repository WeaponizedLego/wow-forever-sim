// Extracts every class's talent trees from an upstream wowsims/forever checkout into data/talents/<class>.json.
//
//   node packages/gamedata/scripts/extract-talents.ts --upstream <path to forever checkout>
//
// Reads upstream `ui/sim/talents/trees/<class>.json` (generated upstream from the game's Trait* tables) and joins
// each talent's spell id to its icon in `assets/database/db.json` (`spellIcons`). Talents stay in upstream's order,
// which is the order of the digits in an engine talent string, and a prerequisite's location becomes its index.
// No Go and no network: plain Node.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLASS_IDS } from '../../contracts/src/game.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const repo = path.resolve(pkg, '../..');
const outDir = path.join(pkg, 'data/talents');

const arg = (name: string): string | undefined => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const upstream = path.resolve(arg('upstream') ?? process.env['FOREVER_UPSTREAM'] ?? '');
const treesDir = path.join(upstream, 'ui/sim/talents/trees');
if (!existsSync(treesDir)) {
  console.error('Pass --upstream <wowsims/forever checkout> (or FOREVER_UPSTREAM).');
  process.exit(1);
}
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim();
const lock = JSON.parse(readFileSync(path.join(repo, 'engine.lock.json'), 'utf8')) as {
  upstream: { commit: string };
};
if (lock.upstream.commit !== commit) {
  console.warn(`warning: upstream is at ${commit}, engine.lock.json pins ${lock.upstream.commit}`);
}

interface Location {
  rowIdx: number;
  colIdx: number;
}
interface UpstreamTalent {
  fieldName?: string;
  fancyName: string;
  location: Location;
  prereqLocation?: Location;
  spellId: number;
  definitionId?: number;
  maxPoints: number;
}
interface UpstreamTree {
  name: string;
  backgroundUrl: string;
  talents: UpstreamTalent[];
}

const db = JSON.parse(readFileSync(path.join(upstream, 'assets/database/db.json'), 'utf8')) as {
  spellIcons?: { id: number; icon?: string }[];
};
const icons = new Map((db.spellIcons ?? []).map((s) => [s.id, s.icon ?? '']));

const failures: string[] = [];
const summary: string[] = [];
mkdirSync(outDir, { recursive: true });
for (const cls of CLASS_IDS) {
  const file = `ui/sim/talents/trees/${cls}.json`;
  const trees = JSON.parse(readFileSync(path.join(upstream, file), 'utf8')) as UpstreamTree[];
  if (trees.length !== 3) failures.push(`${cls}: ${trees.length} trees, expected 3`);
  const out = trees.map((tree) => {
    const at = new Map(tree.talents.map((t, i) => [`${t.location.rowIdx},${t.location.colIdx}`, i]));
    return {
      name: tree.name,
      background: tree.backgroundUrl,
      talents: tree.talents.map((t, i) => {
        const prev = tree.talents[i - 1];
        // The engine string's digit order is the list order, which upstream keeps row by row, left to right.
        if (
          prev &&
          (t.location.rowIdx < prev.location.rowIdx ||
            (t.location.rowIdx === prev.location.rowIdx && t.location.colIdx <= prev.location.colIdx))
        )
          failures.push(`${cls} ${tree.name}: ${t.fancyName} is out of order`);
        const prereq = t.prereqLocation
          ? at.get(`${t.prereqLocation.rowIdx},${t.prereqLocation.colIdx}`)
          : undefined;
        if (t.prereqLocation && prereq === undefined)
          failures.push(`${cls} ${tree.name}: ${t.fancyName}'s prerequisite is not a talent`);
        const icon = icons.get(t.spellId);
        if (!icon) failures.push(`${cls} ${tree.name}: no icon for ${t.fancyName} (spell ${t.spellId})`);
        if (!t.definitionId) failures.push(`${cls} ${tree.name}: ${t.fancyName} has no definitionId`);
        return {
          name: t.fancyName,
          ...(t.fieldName ? { field: t.fieldName } : {}),
          row: t.location.rowIdx,
          col: t.location.colIdx,
          maxPoints: t.maxPoints,
          spellId: t.spellId,
          definitionId: t.definitionId ?? 0,
          icon: icon ?? '',
          ...(prereq !== undefined ? { prereq } : {}),
        };
      }),
    };
  });
  const data = {
    class: cls,
    upstream: { repo: 'wowsims/forever', commit, files: [file, 'assets/database/db.json'] },
    trees: out,
  };
  writeFileSync(path.join(outDir, `${cls}.json`), JSON.stringify(data, null, 2) + '\n');
  summary.push(`| ${cls} | ${out.map((t) => `${t.name} (${t.talents.length})`).join(', ')} |`);
}

const readme = `# Talent trees

Generated by \`scripts/extract-talents.ts\` from [wowsims/forever](https://github.com/wowsims/forever) (MIT) at
\`${commit}\`: \`ui/sim/talents/trees/<class>.json\`, with each talent's icon from \`assets/database/db.json\`
(\`spellIcons\`). Do not edit by hand; rerun the script (engine-sync does, see \`tools/engine-build/README.md\`):

\`\`\`sh
node packages/gamedata/scripts/extract-talents.ts --upstream <forever checkout>
\`\`\`

Each \`<class>.json\` holds the class's three trees in the engine's order. A tree's \`talents\` are in the order of
the digits of an engine talent string (row by row, left to right). \`row\`/\`col\` are 0-based grid cells,
\`prereq\` is the index (in the same tree) of a talent that must be at its maximum first, \`icon\` is the icon
name (\`https://wow.zamimg.com/images/wow/icons/medium/<icon>.jpg\`) and \`definitionId\` is the game's
TraitDefinition id. Upstream has no talent descriptions.

| Class | Trees (talents) |
| ----- | --------------- |
${summary.join('\n')}
`;
writeFileSync(path.join(outDir, 'README.md'), readme);

if (failures.length) {
  console.error(failures.join('\n'));
  process.exit(1);
}
console.log(`wrote ${CLASS_IDS.length} classes to ${path.relative(repo, outDir)}`);
